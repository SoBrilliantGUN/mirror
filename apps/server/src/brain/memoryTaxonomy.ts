export const MEMORY_KIND_GLOSS = `分型顺序：先判断是不是 constraint（硬规则/红线/禁令），是就归 constraint，再判断其它类型。

1. constraint —— 硬规则、禁令、红线（禁止/严禁/不得/必须/永远不要/不能）。示例：「不要在深夜问对方为什么哭」。
2. fact —— 关于用户的可变事实/当前状态（在/正在/目前/现在）。示例：「对方在准备考研」「对方目前没有工作」。
3. preference —— 软性偏好、习惯、风格（喜欢/习惯/希望/更愿意）。示例：「对方更喜欢听具体建议而不是大道理」。
4. episodic —— 带时间锚点的具体事件（昨天/上周/上次/那次/某次）。示例：「上周对方面试挂了两轮，很难过」。
5. profile —— 软特质：性格/价值观/长期模式/情绪模式这类长期稳定的东西（示例：「对方更需要被倾听而非建议」）。区别于 fact：fact 是可变状态，profile 是长期稳定的特质。注意：身份基本信息（名字/性别/年龄/职业/学校/地域/重要关系）不归 profile——它们另有结构化身份字段，由做梦时的反思统一抽取，这里不要抽。`;
