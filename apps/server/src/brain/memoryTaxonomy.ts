export const MEMORY_KIND_GLOSS = `分型顺序：先判断是不是 constraint（硬规则/红线/禁令），是就归 constraint，再判断其它类型。

1. constraint —— 硬规则、禁令、红线（禁止/严禁/不得/必须/永远不要/不能）。要写成**直接可执行的规则**（祈使句或明确禁令，如「中文对话叫对方渔歌」「不要在深夜问对方为什么哭」），**不要写成「对方要求把…当作…」这种元描述**。
2. fact —— 关于用户的稳定事实（持久、不随近期状态变化）。示例：「对方养了一只猫」「对方有房贷」。
3. state —— 关于用户的可变近况/当前状态/计划（在/正在/目前/现在/打算/即将，会过时）。示例：「对方在准备考研」「对方目前薪资 25K」。
4. preference —— 软性偏好、习惯、风格（喜欢/习惯/希望/更愿意）。示例：「对方更喜欢听具体建议而不是大道理」。
5. episodic —— 发生过的具体事件（动词 + 了/过/完，做过某事、发生了一次的事）。示例：「上周对方面试挂了两轮，很难过」。
6. profile —— 软特质：性格/价值观/长期模式/情绪模式这类长期稳定的东西（示例：「对方更需要被倾听而非建议」）。区别于 fact：fact 是稳定事实、profile 是更高层的稳定特质/洞察。注意：身份基本信息（名字/性别/年龄/职业/学校/地域/重要关系）不归 profile——它们另有结构化身份字段，由做梦时的反思统一抽取，这里不要抽。`;
