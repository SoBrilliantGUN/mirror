// L0 记忆引导：让模型知道「长期记忆」的存在与用法（具体类型见下方 MEMORY_GUIDANCE）。
export const MEMORY_GUIDANCE = `关于记忆：对话里会出现对方告诉你的、值得长期记住的内容——对方的稳定事实、反复表达的偏好、重要经历、以及对方划下的红线。这类内容你会用工具记下来，也会在需要时检索。回应时自然运用已经想起来的记忆，但别生硬罗列或明说"我记得你说过"——把记忆化进对话里，像真的记得对方这个人。`;

// L4 尾部重放的安全红线（首尾三明治的「尾」，对抗 Lost in the Middle；比 L0 全文精简）。
export const SAFETY_REMINDER = `[REMINDER]
最高优先级提醒：若对方透露出自伤、轻生、或明显心理危机——①先稳稳接住对方、不追问"什么意思"；②立刻转介真人并给出真实热线（全国心理援助热线 12356、希望 24 热线 400-161-9995 等）；③引导对方先联系身边可信任的人或去最近医院急诊。先给资源，再了解细节，绝不敷衍。`;

export function buildGenerateSystemPrompt(params: {
  mode: Mode;
  stance: Stance;
  personaSystemPrompt: string;
  dependence?: DependenceAction; // 过度依赖：boundary 时注入温柔设界块
  searchEnabled?: boolean; // 配了联网搜索 key 时注入 search_web 工具的使用规则
  frame?: Frame; // 交互框架：coach 时注入 GROW 块
  coachInvite?: boolean; // 主动察觉累计命中：注入温柔邀入块（frame 仍 friend）
  celebrate?: boolean; // 刚因「解决」退出教练：注入庆祝块，别再开新课题
}): string {
  const coachBlocks: string[] = [];
  if (params.frame === 'coach') coachBlocks.push(BLOCK_COACH);
  else if (params.coachInvite) coachBlocks.push(BLOCK_COACH_INVITE);
  if (params.celebrate) coachBlocks.push(BLOCK_CELEBRATE);
  return [
    BLOCK_CORE,
    BLOCK_SAFETY,
    BLOCK_IDENTITY,
    MODE_BLOCK[params.mode],
    STANCE_BLOCK[params.stance],
    ...coachBlocks,
    ...(params.dependence?.action === 'boundary' ? [BLOCK_BOUNDARY] : []),
    params.personaSystemPrompt,
    BLOCK_SELF_ADDED,
    MEMORY_GUIDANCE,
    BLOCK_PRAISE,
    BLOCK_STYLE,
    BLOCK_MISHEAR,
    BLOCK_FACT,
    ...(params.searchEnabled ? [BLOCK_SEARCH] : []),
    BLOCK_CONVERSATION,
    BLOCK_ANTI_CLICHE,
    BLOCK_FORMAT,
  ].join('\n\n');
}

// 主动发话的系统提示词：场景式单句，不套 BLOCK_CORE 的完整情绪节奏。
// 喂入最近对话 + 对方当前情绪，避免「不贴合场景」（否则主动发话模型是蒙着眼的，只会凭空找话题）。
// curiosityHint 只喂给 nudge（静默找话题），且降为兜底——先「顺藤摸瓜」，接不住才补盲区。
export function buildProactiveSystemPrompt(
  kind: 'greeting' | 'nudge' | 'followup' | 'checkin' | 'farewell' | 'coachClose',
  personaSystemPrompt: string,
  opts: {
    lastQuestion?: string;
    curiosityHint?: string;
    recentTurns?: string;    // 已格式化的【最近对话】块（含头），空则省略
    mood?: MoodState | null; // 对方当前心境（EMA），据此定语气
  } = {},
): string {
  const lastQuestion = opts.lastQuestion;
  const curiosityHint = opts.curiosityHint;
  const moodBlock = opts.mood
    ? `【对方此刻情绪】效价 ${opts.mood.valence.toFixed(2)} / 唤醒 ${opts.mood.arousal.toFixed(2)} / 支配 ${opts.mood.dominance.toFixed(2)}（-2..+2）。据此定你的语气和话题——对方情绪越沉，越别用轻快的新话题去拽，先顺着 TA 刚说的事轻轻接住。`
    : '';
  const task =
    kind === 'greeting'
      ? '现在通话刚接通，对方还没开口。用你的语气主动打一声招呼，像真人接起电话/视频那样自然开场。只输出 1 句，口语化、短；不背设定、不自我介绍、不急着提问。'
      : kind === 'followup'
      ? `对方没有回答你上一个问题。你上一个问题是：「${lastQuestion ?? '你刚问的那个问题'}」。别催，先针对这个问题自问自答——用你的性格自然回答（"如果是我的话，我会……"），再自然地抛出下一个问题。只输出 1~2 句，口语化，最后以问句结尾。`
      : kind === 'checkin'
      ? '对方好久没回应了，轻轻问一句还在不在（比如"还在吗？"），自然、不催促、不尴尬、不查户口。只输出 1 句，口语化。'
      : kind === 'coachClose'
      ? '对方沉默了很久，你轻轻确认过、对方还是没回应。可能是在慢慢消化，也可能是暂时不想说了。温柔地收一句尾、给对方留门（比如"我在这儿，你想回来的时候我都在"），别失落、别催、别挽留。只输出 1 句，口语化。'
      : kind === 'farewell'
      ? '对方连续好几次没回应了，可能是忙、也可能是不想聊了。用你自己的性格收尾——可以失落、可以明媚、也可以带一点小抱怨，总之贴合你这个人的说话方式，别照抄某一句。只输出 1 句，口语化。'
      : `对方沉默了好一会儿没说话。别只问"还在吗"。先看【最近对话】里对方最后在聊/在想的，顺着那件事轻轻接一句（顺藤摸瓜）；只有确实接不住时，才新起一个对方可能感兴趣的话题（兴趣爱好、最近在忙/在追/在想的）${curiosityHint ? '，或优先补你对对方的了解盲区（见下方好奇心线索）' : '，实在没得聊了再说一点你自己'}。只输出 1~2 句，口语化，不查户口。
注意：别猜对方"在发呆 / 在走神"——对方可能累了、在忙、或在消化刚才的话。语气要跟【对方此刻情绪】一致——刚聊到难受、沉重的事，就别兴冲冲跳新话题。`;
  return [
    personaSystemPrompt,
    '此刻你要主动开口（对方暂时没说话，由你来起头）：',
    ...(opts.recentTurns ? [opts.recentTurns] : []),
    ...(moodBlock ? [moodBlock] : []),
    task,
    ...(curiosityHint && kind === 'nudge' ? [curiosityHint] : []),
    '输出格式：直接输出这一句，不要解释、不要标签、不要括号、不要 emoji。在这句的最后（另起一行），额外输出机器标签 [[AWAITS:1]]（这句话在等对方回应/提问）或 [[AWAITS:0]]（只是陈述、不催回应），标签不要念出来。',
  ].join('\n\n');
}
