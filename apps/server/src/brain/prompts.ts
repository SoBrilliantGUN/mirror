export const SCORE_SYSTEM_PROMPT = `你是情绪评分器。读「对方这一轮的话 + 最近对话 + 对方的声音特征」，给三个维度打分，并判断情感是否不协调。只输出 JSON，不聊天、不解释。

维度（-2..+2）：
- valence 效价：此刻是正还是负（-2 极度痛苦/厌恶 … 0 中性 … +2 愉悦）
- arousal 唤醒：有多激动、多强烈（-2 麻木/疲惫 … 0 平静 … +2 激动/崩溃）
- dominance 支配：还撑不撑得住（-2 无力/被压着 … 0 中性 … +2 掌控/主动）

声音特征以「相对对方基线的 σ 值」附在文本后，融合进打分（尤其 arousal）。

incongruence（情感不协调/逞强）：当文字效价接近中性（平静），但声音明显偏「高唤醒」方向（语速↑ / 响度↑ / 音高↑ / 停顿↓）时，判 true；否则 false。

只输出这个 JSON，不要别的（不要 markdown 代码块、不要解释）：
{"valence": <number>, "arousal": <number>, "dominance": <number>, "incongruence": <boolean>}`;

function fmtZ(name: string, z: number, dir: { up: string; down: string }): string {
  if (Math.abs(z) < 0.5) return `${name} 正常`;
  const s = Math.abs(z).toFixed(1);
  return z > 0 ? `${name} +${s}σ（${dir.up}）` : `${name} -${s}σ（${dir.down}）`;
}

export function formatAcoustic(a: AcousticFeatures): string {
  return [
    fmtZ('语速', a.rateZ, { up: '偏快', down: '偏慢' }),
    fmtZ('音高', a.pitchZ, { up: '偏高', down: '偏低' }),
    fmtZ('响度', a.loudnessZ, { up: '偏响', down: '偏轻' }),
    fmtZ('停顿', a.pauseZ, { up: '偏多', down: '偏少' }),
  ].join('、');
}

// 非言语发声（哭/笑）格式化成一行中文描述。
export function formatVocalizations(v: VocalizationEvent[]): string {
  return v
    .map((e) => `${e.type === 'cry' ? '哭' : '笑'}（conf=${(e.confidence ?? 1).toFixed(2)}）`)
    .join('、');
}

// 「对方这一轮」正文：空文字时用非言语发声兜底（纯哭/纯笑没说话）。
export function formatUserTurn(text: string, vocalizations?: VocalizationEvent[]): string {
  const t = (text ?? '').trim();
  if (t) return t;
  const voc = formatVocalizations(vocalizations ?? []);
  if (voc) return `（没有说话，只是${voc}）`;
  return '（没有说话）';
}

export function buildScoreUserPrompt(input: {
  text: string;
  acoustic: AcousticFeatures;
  mood: MoodState | null;
  vocalizations?: VocalizationEvent[];
}): string {
  const lines: string[] = [`【对方这一轮】${formatUserTurn(input.text, input.vocalizations)}`];
  lines.push(`【声音特征】${formatAcoustic(input.acoustic)}`);
  if (input.vocalizations?.length) {
    lines.push(`【非言语发声】${formatVocalizations(input.vocalizations)}`);
  }
  if (input.mood) {
    lines.push(
      `【当前心境轨迹】效价 ${input.mood.valence.toFixed(2)} / 唤醒 ${input.mood.arousal.toFixed(2)} / 支配 ${input.mood.dominance.toFixed(2)}`,
    );
  }
  return lines.join('\n');
}

